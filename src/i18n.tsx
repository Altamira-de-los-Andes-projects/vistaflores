export const COPY: Record<Lang, Copy> = { es, en, pt };

// ─── Context ──────────────────────────────────────────────────────────────────
const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: 'en',
  setLang: () => {},
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const stored = localStorage.getItem('vf-lang');
      if (stored === 'es' || stored === 'en' || stored === 'pt') return stored;
    } catch (e) {}
    return 'en';
  });
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem('vf-lang', l);
    } catch (e) {}
  };
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}

export function useT(): Copy {
  return COPY[useLang().lang];
}
