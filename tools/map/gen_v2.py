# Writes src/data/ucomap.ts for the v2 map (satellite base public/assets/uco-sat.webp, 2400 px wide).
import os, json, math
D = os.path.dirname(os.path.abspath(__file__))
L = json.load(open(os.path.join(D, 'v2_lines.json')))
Zn = json.load(open(os.path.join(D, 'zones_v2.json')))
W, H = L['frame']
LON_W, LON_E, LAT_N, LAT_S, Z = -69.52, -68.90, -33.54, -33.89, 13
def merc(lon, lat):
    n = 2 ** Z * 256
    return (lon + 180) / 360 * n, (1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n
X0, Y0 = merc(LON_W, LAT_N); X1, _ = merc(LON_E, LAT_S); S = W / (X1 - X0)
def P(lon, lat):
    x, y = merc(lon, lat); return [round((x - X0) * S), round((y - Y0) * S)]
m_per_px = 156543.03 * math.cos(math.radians(33.72)) / 2 ** Z / S

def rdp(pts, eps):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1; n = math.hypot(dx, dy)
    best, idx = 0, 0
    for i in range(1, len(pts) - 1):
        x, y = pts[i]
        d = abs(dx * (y1 - y) - dy * (x1 - x)) / n if n else math.hypot(x - x1, y - y1)
        if d > best: best, idx = d, i
    return rdp(pts[:idx + 1], eps)[:-1] + rdp(pts[idx:], eps) if best > eps else [pts[0], pts[-1]]

def path(pts, close=False):
    return 'M' + 'L'.join(f'{round(x)} {round(y)}' for x, y in pts) + ('Z' if close else '')

# stitch river ways into one polyline (west → east) where they touch
ways = [list(map(tuple, w)) for w in L['river']]
line = ways.pop(0)
while ways:
    for i, w in enumerate(ways):
        if w[0] == line[-1]: line += w[1:]; ways.pop(i); break
        if w[-1] == line[0]: line = w[:-1] + line; ways.pop(i); break
        if w[-1] == line[-1]: line += w[::-1][1:]; ways.pop(i); break
        if w[0] == line[0]: line = w[::-1][:-1] + line; ways.pop(i); break
    else:
        break
river = path(rdp(line, 0.8)) + ''.join(path(rdp(w, 0.8)) for w in ways)

zones = {k: path(rdp(Zn[k], 0.6), True) for k in ('altamira', 'laConsulta', 'vistaFlores')}
pts = {
    'altamiraLabel': [round(v) for v in Zn['altamira_c']],
    'laConsultaLabel': P(-69.075, -33.690),
    'vistaFloresLabel': [round(v) for v in Zn['vistaFlores_c']],
    'tunuyan': P(-69.0154, -33.5813),
    'sanCarlos': P(-69.0404, -33.7721),
    'riverLabel': [1772, 496],
    'andes': P(-69.43, -33.70),
    'mendozaArrow': P(-69.03, -33.55),
}
out = f"""// Generated by tools/map/gen_v2.py — do not edit by hand.
// Overlay for public/assets/uco-sat.webp ({W}×{H}): Sentinel-2 cloudless 2016 by EOX (CC BY 4.0,
// contains modified Copernicus Sentinel data) with a hillshade from AWS Terrain Tiles.
// Zones follow the INV resolutions for each Geographical Indication: Vista Flores C.11/2012 (district
// limits, OpenStreetMap), La Consulta 19/2014, Paraje Altamira 82-E/2017. River, RN40 and streets ©
// OpenStreetMap contributors (ODbL). Limits are drawn at map scale, not survey accuracy.
export const UCO_W = {W};
export const UCO_H = {H};
export const UCO_RIVER = '{river}';
export const UCO_ZONES = {json.dumps(zones)} as const;
export const UCO_PT = {json.dumps(pts)} as const;
export const UCO_KM5 = {round(5000 / m_per_px)};
"""
open(os.path.join(D, '..', '..', 'src', 'data', 'ucomap.ts'), 'w', encoding='utf8').write(out)
print(len(out) / 1024, 'KB', pts, 'km5', round(5000 / m_per_px), 'leftover river ways', len(ways))
